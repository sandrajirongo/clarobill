"""Engine→web boundary contract test (Pydantic side).

Generates a fixture JSON file containing one BillingError instance per
BillingErrorCode, dumped exactly as the engine writes them to
analysis_results.errors. The web vitest counterpart at
apps/web/src/lib/__tests__/engine-boundary.contract.test.ts reads the same
file and parses it with BillingErrorSchema.

Either the fixture is regenerated by running this test, OR a Pydantic-side
shape change breaks the parse on the web side. Both halves of the contract
move together; neither can drift silently.

The fixture is checked into git. Running this test is idempotent: the file
content is deterministic, so a clean run never produces an unexpected diff.
"""

from __future__ import annotations

import json
from decimal import Decimal
from pathlib import Path

from app.models.bill import (
    BillingError,
    BillingErrorCode,
    ErrorSeverity,
)


_FIXTURE_PATH = (
    Path(__file__).resolve().parent.parent.parent.parent
    / "web"
    / "src"
    / "lib"
    / "__tests__"
    / "fixtures"
    / "engine-billing-error.json"
)


def _representative_error(code: BillingErrorCode) -> BillingError:
    """Build one BillingError per code with stable, hand-chosen values.

    Values are deterministic so the fixture file diff is empty whenever the
    generator runs against an unchanged engine. Edit a value here only when
    the schema itself changes.
    """
    return BillingError(
        code=code,
        severity=ErrorSeverity.CRITICAL,
        affected_line_item_ids=[f"li-{code.value.lower()}-1", f"li-{code.value.lower()}-2"],
        description=f"Synthetic {code.value} finding for boundary contract test",
        estimated_overcharge=Decimal("123.45"),
        medicare_benchmark_rate=Decimal("78.90"),
    )


def _generate_fixture() -> list[dict[str, object]]:
    return [
        _representative_error(code).model_dump(by_alias=True, mode="json")
        for code in sorted(BillingErrorCode, key=lambda c: c.value)
    ]


def test_billing_error_fixture_matches_disk() -> None:
    """The engine-side dump and the on-disk fixture must agree.

    If this fails, either:
      (a) BillingError schema changed — regenerate the fixture by running
          `python -m apps.engine.tests.services.test_billing_error_fixture_export`
          (or just delete the file; the assertion below writes it on first run).
      (b) The fixture was hand-edited away from the engine output — undo.

    The web-side counterpart parses the same file, so any drift surfaces in
    BOTH the engine pytest AND the web vitest.
    """
    expected = _generate_fixture()

    if not _FIXTURE_PATH.exists():
        # First run — bootstrap the fixture so CI has something to compare on
        # subsequent runs.
        _FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
        _FIXTURE_PATH.write_text(json.dumps(expected, indent=2, sort_keys=True) + "\n")

    actual_text = _FIXTURE_PATH.read_text()
    expected_text = json.dumps(expected, indent=2, sort_keys=True) + "\n"

    assert actual_text == expected_text, (
        "Engine BillingError dump diverged from on-disk boundary fixture at "
        f"{_FIXTURE_PATH}. Regenerate the fixture (delete the file and re-run "
        "this test) and update the web-side parser if the shape change is "
        "intentional."
    )


def test_fixture_covers_every_billing_error_code() -> None:
    """Regression net: every BillingErrorCode must appear in the fixture so the
    web boundary parses every variant the engine might emit."""
    expected = _generate_fixture()
    codes = {item["code"] for item in expected}
    assert codes == {c.value for c in BillingErrorCode}


def test_fixture_keys_are_camel_case() -> None:
    """The whole point of the boundary fixture: every key must be camelCase."""
    expected = _generate_fixture()
    snake_markers = {"affected_line_item_ids", "estimated_overcharge", "medicare_benchmark_rate"}
    for item in expected:
        for key in item:
            assert key not in snake_markers, (
                f"Found legacy snake_case key {key!r} in BillingError dump — "
                "alias_generator regression."
            )
